def best_f1_threshold(y_true, scores):
    precision, recall, thresholds = precision_recall_curve(y_true, scores)
    f1 = 2 * precision * recall / (precision + recall + 1e-12)

    # precision_recall_curve returns one extra precision/recall point.
    best_index = np.argmax(f1[:-1])
    return float(thresholds[best_index]), float(f1[best_index])


def evaluate_scores(y_true, scores, threshold, top_fraction=0.10):
    predictions = (scores >= threshold).astype(int)

    k = max(1, int(len(y_true) * top_fraction))
    top_index = np.argsort(scores)[::-1][:k]
    precision_at_k = y_true[top_index].mean()
    base_rate = y_true.mean()

    tn, fp, fn, tp = confusion_matrix(y_true, predictions).ravel()

    return {
        "accuracy": accuracy_score(y_true, predictions),
        "precision": precision_score(y_true, predictions, zero_division=0),
        "recall": recall_score(y_true, predictions, zero_division=0),
        "f1": f1_score(y_true, predictions, zero_division=0),
        "roc_auc": roc_auc_score(y_true, scores),
        "ap": average_precision_score(y_true, scores),
        "precision_at_10": precision_at_k,
        "lift_at_10": precision_at_k / base_rate,
        "threshold": threshold,
        "tn": int(tn),
        "fp": int(fp),
        "fn": int(fn),
        "tp": int(tp),
    }


def result_row(name, y_true, scores, threshold):
    row = evaluate_scores(y_true, scores, threshold)
    row["model"] = name
    return row

